import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import type { TransformedToken } from "style-dictionary";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function cssName(token: TransformedToken): string {
  return `d2s-${token.path.join("-")}`;
}

function camelName(token: TransformedToken): string {
  return token.path
    .map((part, index) => {
      const clean = part.replace(/[^a-zA-Z0-9]/g, "");
      if (!clean) return "";
      if (index === 0) return clean;
      return clean.charAt(0).toUpperCase() + clean.slice(1);
    })
    .join("");
}

function sourceValue(token: TransformedToken): string {
  const original = token.original as { $value?: unknown; value?: unknown } | undefined;
  const raw = original?.$value ?? original?.value ?? token.$value ?? token.value;
  return String(raw);
}

function isDimension(token: TransformedToken): boolean {
  const original = token.original as { $type?: string; type?: string } | undefined;
  return (token.$type ?? token.type ?? original?.$type ?? original?.type) === "dimension";
}

const header = "Generated by packages/design-tokens/scripts/build.ts. Do not edit.";

const sd = new StyleDictionary({
  usesDtcg: true,
  source: [path.join(packageRoot, "tokens.json")],
  log: { warnings: "disabled", verbosity: "silent" },
  platforms: {
    css: {
      buildPath: path.join(packageRoot, "generated/css/"),
      files: [{ destination: "tokens.css", format: "d2s/css" }]
    },
    scss: {
      buildPath: path.join(packageRoot, "generated/scss/"),
      transforms: ["size/rpx"],
      files: [{ destination: "tokens.scss", format: "d2s/scss" }]
    },
    swift: {
      buildPath: path.join(packageRoot, "generated/swift/"),
      files: [{ destination: "Tokens.swift", format: "d2s/swift" }]
    }
  },
  hooks: {
    transforms: {
      "size/rpx": {
        type: "value",
        filter: (token) => isDimension(token as TransformedToken),
        transform: (token) => {
          const amount = Number.parseFloat(sourceValue(token as TransformedToken));
          return `${amount * 2}rpx`;
        }
      }
    },
    formats: {
      "d2s/css": ({ dictionary }) => {
        const lines = dictionary.allTokens.map((token) => `  --${cssName(token)}: ${sourceValue(token)};`);
        return `/* ${header} */\n:root {\n${lines.join("\n")}\n}\n`;
      },
      "d2s/scss": ({ dictionary }) => {
        const lines = dictionary.allTokens.map((token) => {
          const value = isDimension(token) ? token.$value ?? token.value : sourceValue(token);
          return `$${cssName(token)}: ${value};`;
        });
        return `// ${header}\n${lines.join("\n")}\n`;
      },
      "d2s/swift": ({ dictionary }) => {
        const lines = dictionary.allTokens.map((token) => {
          const name = camelName(token);
          if (isDimension(token)) {
            const amount = Number.parseFloat(sourceValue(token));
            return `    public static let ${name}: Double = ${amount}`;
          }
          return `    public static let ${name} = "${sourceValue(token)}"`;
        });
        return `// ${header}\npublic enum D2STokens {\n${lines.join("\n")}\n}\n`;
      }
    }
  }
});

mkdirSync(path.join(packageRoot, "generated/css"), { recursive: true });
mkdirSync(path.join(packageRoot, "generated/scss"), { recursive: true });
mkdirSync(path.join(packageRoot, "generated/swift"), { recursive: true });

await sd.buildAllPlatforms();
console.log(`design tokens written to ${path.join(packageRoot, "generated")}`);
