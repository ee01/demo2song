import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function readJson(name: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path.join(packageRoot, name), "utf8")) as Record<string, unknown>;
}

function flatten(input: unknown, prefix = ""): Record<string, string> {
  if (typeof input === "string") {
    return prefix ? { [prefix]: input } : {};
  }
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    return {};
  }
  const result: Record<string, string> = {};
  for (const [key, value] of Object.entries(input)) {
    const next = prefix ? `${prefix}.${key}` : key;
    Object.assign(result, flatten(value, next));
  }
  return result;
}

const copy = readJson("zh-Hans.json");
const errors = readJson("errors.json") as Record<string, string>;
const flatCopy = flatten(copy);
const flatErrors = Object.fromEntries(Object.entries(errors).map(([code, text]) => [`errors.${code}`, text]));
const strings = { ...flatCopy, ...flatErrors };

const generatedDir = path.join(packageRoot, "src/generated");
const xcstringsDir = path.join(packageRoot, "generated");
mkdirSync(generatedDir, { recursive: true });
mkdirSync(xcstringsDir, { recursive: true });

const copySource = `// Generated by packages/i18n/scripts/build.ts. Do not edit.
export const zhHans = ${JSON.stringify(copy, null, 2)} as const;

export const flatCopy: Record<string, string> = ${JSON.stringify(flatCopy, null, 2)};
`;
writeFileSync(path.join(generatedDir, "copy.ts"), copySource);

const xcstrings = {
  sourceLanguage: "zh-Hans",
  strings: Object.fromEntries(
    Object.entries(strings).map(([key, value]) => [
      key,
      {
        localizations: {
          "zh-Hans": {
            stringUnit: {
              state: "translated",
              value
            }
          }
        }
      }
    ])
  ),
  version: "1.0"
};
writeFileSync(path.join(xcstringsDir, "Localizable.xcstrings"), `${JSON.stringify(xcstrings, null, 2)}\n`);
console.log(`i18n strings: ${Object.keys(strings).length}`);
